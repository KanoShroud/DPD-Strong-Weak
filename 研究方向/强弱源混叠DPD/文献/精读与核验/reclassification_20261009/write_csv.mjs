import fs from 'node:fs/promises';
import {Workbook} from '@oai/artifact-tool';
const root='F:/SourceCount_DPD_E2E/';
const out=root+'outputs_e2e/literature/reclassification_20261009/';
const matrix=JSON.parse(await fs.readFile(out+'csv_matrix.json','utf8'));
const wb=await Workbook.fromCSV(await fs.readFile(root+'文献精读结果.csv','utf8'),{sheetName:'文献'});
const sh=wb.worksheets.getItem('文献');
sh.getRange('A1').write(matrix);
wb.recalculate();
const col=n=>{let s='';for(;n;n=Math.floor((n-1)/26))s=String.fromCharCode(65+(n-1)%26)+s;return s;};
const back=sh.getRange(`A1:${col(matrix[0].length)}${matrix.length}`).values;
if(JSON.stringify(back)!==JSON.stringify(matrix))throw new Error('Artifact range round-trip mismatch');
const quote=x=>'"'+String(x??'').replaceAll('"','""')+'"';
const csv=m=>m.map(r=>r.map(quote).join(',')).join('\r\n')+'\r\n';
// CSV is a plain table; serialize the verified Artifact Tool values without XLSX-only formatting.
const mainBom=(await fs.readFile(out+'文献精读结果.csv.before','utf8')).startsWith('\uFEFF')?'\uFEFF':'';
await fs.writeFile(root+'文献精读结果.csv',mainBom+csv(back),'utf8');
const fields=['编号','旧编号','分类','归档子类','标题','DOI','ZoteroKey'];
const ix=fields.map(x=>matrix[0].indexOf(x));
await fs.writeFile(root+'参考文献编号对照.csv','\uFEFF'+csv([fields,...back.slice(1).map(r=>ix.map(i=>r[i]))]),'utf8');
console.log(JSON.stringify({rows:back.length-1,columns:back[0].length,verified:true}));
const detail=JSON.parse(await fs.readFile(out+'detail_matrix.json','utf8'));
const dw=await Workbook.fromCSV(await fs.readFile(root+'文献精读结果_详版.csv','utf8'),{sheetName:'历史精读'});
const ds=dw.worksheets.getItem('历史精读');
ds.getRange('A1').write(detail);
dw.recalculate();
const dv=ds.getRange(`A1:${col(detail[0].length)}${detail.length}`).values;
if(JSON.stringify(dv)!==JSON.stringify(detail))throw new Error('Historical CSV round-trip mismatch');
const detailBom=(await fs.readFile(out+'文献精读结果_详版.csv.before','utf8')).startsWith('\uFEFF')?'\uFEFF':'';
await fs.writeFile(root+'文献精读结果_详版.csv',detailBom+csv(dv),'utf8');
console.log(JSON.stringify({historicalRows:dv.length-1,verified:true}));
