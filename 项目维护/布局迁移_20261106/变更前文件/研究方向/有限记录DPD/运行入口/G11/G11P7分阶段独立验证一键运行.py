"""PyCharm: run once to complete the frozen P7 comparison and its reference subset.

The pilot must have passed first. Rerunning resumes sealed whole-method results.
Formal observations are NOT generated by --check-only. No 8192-point experiment.
"""
import argparse
from datetime import datetime, timezone
import math
import msvcrt
from pathlib import Path
import sys
import time

ROOT = Path(__file__).resolve().parents[3]
sys.path.insert(0, str(ROOT))

from 统一模型代码.gates.g11.model_integration.p7 import (
    BASE, create, execute, read, sha, verify, write, task_list,
)
from 统一模型代码.gates.g11.model_integration.p7_report import make_report

# None uses the rounded-up conservative pilot envelope, printed before running.
# Set an explicit larger budget only after reviewing the preparation estimate.
MAX_HOURS = None


def main():
    parser = argparse.ArgumentParser()
    parser.add_argument('--check-only', action='store_true')
    parser.add_argument('--redraw', type=Path)
    args = parser.parse_args()
    if args.redraw:
        make_report(args.redraw)
        return
    release = read(BASE/'release.json')
    pilot = (ROOT/release['pilot']).resolve(strict=True)
    checks = (ROOT/release['checks']).resolve(strict=True)
    if sha(pilot/'contract.json') != release['source_contract_sha'] or sha(checks/'checks.json') != release['checks_sha']:
        raise RuntimeError('准备证据身份不一致，请停止并核查。')
    if not read(checks/'checks.json')['passed'] or not read(pilot/'audit.json')['completed']:
        raise RuntimeError('短测尚未完成，不启动正式批次。')
    verify(pilot, read(pilot/'contract.json'))
    budget = release['budget']
    hours = float(MAX_HOURS) if MAX_HOURS is not None else max(1., math.ceil(budget['max_layout_envelope_hours']))
    print(f'实测外推约 {budget["estimate_hours"]:.2f} 小时；最大构型成本包络约 {budget["max_layout_envelope_hours"]:.2f} 小时。')
    print(f'首次运行累计安全预算：{hours:.1f} 小时。含240条混合观测、四版本960次及8次有限条件搜索参照。')
    print('方法顺序轮换，完整单例结束后保存；达到累计预算才暂停，不按秒截断定位。')
    if args.check_only:
        print('入口及证据检查通过；未生成正式数据、未启动求解。')
        return
    if release['status'] != 'READY_FOR_USER_RUN' and MAX_HOURS is None:
        raise RuntimeError('估算超过准备范围，需要确认预算后设置MAX_HOURS；未启动。')
    # OS lock is released even if PyCharm stops the process; no stale PID lock.
    with (BASE/'oneclick.lock').open('a+b') as lock:
        if lock.tell() == 0:
            lock.write(b'0')
            lock.flush()
        lock.seek(0)
        try:
            msvcrt.locking(lock.fileno(), msvcrt.LK_NBLCK, 1)
        except OSError as exc:
            raise RuntimeError('已有P7一键任务正在运行，请不要并发启动。') from exc
        selected = None
        existing = sorted(BASE.glob('formal_*'), reverse=True)
        if existing:
            folder = existing[0]
            contract = read(folder/'contract.json')
            if contract['preparation'] != release['source_contract_sha']:
                raise RuntimeError('已有正式目录对应另一准备版本，不能静默换版本或重跑。')
            if contract['tasks'] != task_list('formal') or contract['mode'] != 'formal':
                raise RuntimeError('正式任务清单与批准协议不符。')
            verify(folder, contract)
            selected = folder, contract
        if selected is None:
            selected = create('formal', hours, release['source_contract_sha'])
        folder, contract = selected
        print('正式结果目录：', folder, flush=True)
        print('本目录冻结预算：', contract['budget_hours'], '小时；恢复不重置累计账目。', flush=True)
        if not (folder/'entry_identity.json').exists():
            write(folder/'entry_identity.json', dict(source=str(Path(__file__)), sha=sha(Path(__file__))))
        execute(folder, contract)
        ledger = read(folder/'ledger.json')
        reporting = dict(start_utc=datetime.now(timezone.utc).isoformat(), observed_seconds=0.,
                         status='RUNNING', stage='REPORT_ONLY')
        ledger['attempts'].append(reporting)
        write(folder/'ledger.json', ledger)
        tick = time.perf_counter()
        try:
            make_report(folder)
            reporting['status'] = 'COMPLETED'
        except BaseException:
            reporting['status'] = 'FAILED_OR_INTERRUPTED'
            raise
        finally:
            reporting['observed_seconds'] = time.perf_counter()-tick
            write(folder/'ledger.json', ledger)
        if read(folder/'audit.json')['completed']:
            print('P7完整比较已完成。请将此结果目录交给Codex回读。', flush=True)
        else:
            print('已保存部分结果；尚未完成，不作为完整比较结论。', flush=True)


if __name__ == '__main__':
    main()
